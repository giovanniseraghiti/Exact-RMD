% ================================================================
% Script supporting the contribution
%     "The ReLU Matrix Decomposition: NP-Hardness, Ill-Posedness, and ReLU-Rank"  
% authors: Giovanni Seraghiti, Arnaud Vandaele, and Nicolas Gillis
% ================================================================
%
% We compute a rank-3 RMD of the 10x10 identity matrix using Naive-RMD and
% we initialize it with a noisy exact solutioj of the problem. Our aim is
% to investigate the local convergence of the algorithm.
% 
% Specifically, given W and H, we generate  X_noisy by flipping the sign of
% randomly selected entries in WH. According to the geometric representation of RMD,
% flipping the sign in the exact solution means moving the points-hyperplanes 
% representation by randomly switching the scalar product between points and 
% the normal vector to hyperplanes separating them.
%
% The solver is expected to reconstruct:
%
%       X_noisy ~= max(0, Theta)
% ================================================================


clear;
clc;
close all;
addpath(fullfile(fileparts(mfilename('fullpath')), '..', 'Algorithms_and_utils'));

%% ========================= INPUT ==============================

load('../Algorithms_and_utils/gurobi_identity_WH.mat');
%load('W_id.mat'); load("H_id.mat");  % Load the solution computed using Gurobi
[m,r] = size(W);

% Noise levels
noise_type=0;
    if noise_type==1
        %noise_levels = [0, 0.01, 0.02, 0.05, 0.10, 0.20, 0.50, 1.00];
        noise_levels=[0,100,200,300,400,500];
    else
        % Percentage of entries whose sign is flipped 
        noise_levels = [0 0.10 0.20 0.30 0.4 0.50 0.6 0.7 0.8 0.9 1.00];
        %noise_levels = [0 0.10 ];
    end

% Number of independent noise realizations for each level
n_trials = 10;

% Random seed for reproducibility
rng(1);

%% ========================= PARAM ==============================

% parameters for Naive-RMD
 param.maxit = 10000;
 param.tol = 1e-12;
 param.tol_err=1e-12;
 param.display = 1;


%% ========================= SETUP ==============================

% Clean matrix generated by W and H
WH = W * H;
% Number of entries 
N = numel(WH);

% Reference matrix
X = eye(m);

% Norm of the reference matrix
normX = norm(X, 'fro');

n_noise = length(noise_levels);

% Storage
final_error = zeros(n_noise, n_trials);
iterations   = zeros(n_noise, n_trials);
times        = zeros(n_noise, n_trials);

%% ========================= MAIN LOOP ==========================

for k = 1:n_noise
    
    if noise_type==1
        sigma = noise_levels(k);
    else
        noise = noise_levels(k); sigma=noise;
        % Number of entries whose sign will be flipped 
        n_flip = round(noise * N);
    end

    fprintf('\n============================================\n');
    fprintf('Noise level: %.4f\n', sigma);
    fprintf('============================================\n');

    for trial = 1:n_trials

        rng(trial)
        if noise_type==1
            %% Generate additive noise
    
            % Gaussian additive noise.
            %
            % The standard deviation is scaled with respect
            % to the Frobenius norm of the clean matrix.
            %
            % This gives approximately:
            %
            %       ||E||_F / ||X||_F ~= sigma
    
            E = randn(size(WH));
    
            if norm(E, 'fro') > 0
                E = sigma * normX * E / norm(E, 'fro');
            end
    
            % Noisy input to the solver
            X_noisy = WH + E;
        else %flipping sign noise
            X_noisy = WH; 

            % Randomly select entries 
            idx = randperm(N,n_flip); 

            % Flip their sign 
            X_noisy(idx) = -X_noisy(idx);
        end
        %% Run Naive_NMD
        param.Theta0=X_noisy;
        %param.Theta0=randn(m);
        [Theta, err, i, time] = Naive_NMD(X, r, param);

        %% Store results

        final_error(k, trial) = err(end);
        iterations(k, trial) = i;
        times(k, trial)      = time(end);

        fprintf('Trial %d: error = %.4e, iterations = %d, time = %.4f s\n', ...
            trial, final_error(k, trial), iterations(k, trial), times(k, trial));

    end
end

%% ========================= RESULTS ============================

% Average over trials
mean_error = mean(final_error, 2);
mean_iter  = mean(iterations, 2);
mean_time  = mean(times, 2);

% Relative noise level
noise_percent = 10 * noise_levels(:);

% Create table
Results = table( ...
    noise_percent, ...
    mean_error, ...
    mean_iter, ...
    mean_time, ...
    'VariableNames', { ...
    'NoisePercent', ...
    'FinalRelativeError', ...
    'Iterations', ...
    'TimeSeconds'});

disp(' ');
disp('================ RESULTS ================');
disp(Results);

%% ========================= PLOT ==============================

figure('Color', 'w');

plot(noise_percent, mean_error, ...
    '-o', ...
    'LineWidth', 2.0, ...
    'MarkerSize', 8);

grid on;
box on;

xlabel('Number of entries with fliped sign', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 18);

ylabel('Final relative error','FontName', 'Times New Roman','FontSize', 18);

